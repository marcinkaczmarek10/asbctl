#!/usr/bin/env bash
# Write THIRD_PARTY_LICENSES: the licence and NOTICE text of every module that the asbctl binary
# links on darwin, linux and windows. The Python package carries a copy, because license-files
# cannot point outside python/. CI runs this script and fails when either file is stale.
# Usage: scripts/third-party-licenses.sh
set -euo pipefail

export LC_ALL=C
cd "$(dirname "$0")/.."
output=THIRD_PARTY_LICENSES
oses=(darwin linux windows)

work="$(mktemp -d)"
# The module cache and go-licenses write read-only files.
trap 'chmod -R u+w "$work"; rm -rf "$work"' EXIT

GOBIN="$work/bin" go install github.com/google/go-licenses/v2@v2.0.1
main_module="$(go list -m)"

mkdir "$work/all"
for goos in "${oses[@]}"; do
  GOOS="$goos" CGO_ENABLED=0 "$work/bin/go-licenses" save ./cmd/asbctl --save_path="$work/$goos" 2>/dev/null
  chmod -R u+w "$work/$goos"
  cp -R "$work/$goos/." "$work/all/"
  chmod -R u+w "$work/all"
  GOOS="$goos" CGO_ENABLED=0 go list -deps \
    -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}}{{end}}{{end}}' ./cmd/asbctl >> "$work/modules.raw"
done
sort -u "$work/modules.raw" > "$work/modules"

{
  echo "Third-party licences of the modules that asbctl links."
  echo "Generated by scripts/third-party-licenses.sh. Do not edit by hand."
  (cd "$work/all" && find . -type f -exec dirname {} \; | sed 's|^\./||' | sort -u) |
    while read -r package; do
      [[ "$package" == "$main_module"* ]] && continue
      module_line="$(awk -v package="$package" '
        index(package "/", $1 "/") == 1 && length($1) > best { best = length($1); line = $0 }
        END { print line }' "$work/modules")"
      echo
      echo "================================================================================"
      echo "$package (module $module_line)"
      echo "================================================================================"
      for file in "$work/all/$package"/*; do
        echo
        echo "--- $(basename "$file") ---"
        echo
        cat "$file"
      done
    done
} > "$output"
cp "$output" "python/$output"
